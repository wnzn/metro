class Run:
    def __init__(self, stack, directory, server_binary, connector, timeout):
        self.stack, self.directory, self.connector = stack, Path(directory), connector
        self.deadline = time.monotonic() + timeout
        self.vendors = {name: serve_fixture(stack, MediaVendor(name))
                        for name in ("alice", "device", "bob", "carol")}
        self.tokens = {user: token() for user in ("alice", "bob", "carol")}
        self.secrets = [*self.tokens.values(), *(v.key for v in self.vendors.values())]
        self.env = clean_env(directory)
        self.port = server_port()
        server = start_child(stack, "library server", server_binary, self.directory, self.env | {
            "METRO_BIND": f"{HOST}:{self.port}",
            "METRO_DB": str(self.directory / "metro.sqlite"),
            "METRO_DEV_USERS": json.dumps(self.tokens),
            "METRO_ORG_ADMINS": json.dumps(["alice"]),
            "METRO_PROVIDER_MASTER_KEY": base64.b64encode(bytes.fromhex(token())).decode("ascii"),
            "METRO_PROVIDER_ALLOWED_BASE_URLS": json.dumps(
                [v.base_url for v in self.vendors.values()]),
        })
        self.children = [server]
        wait_for_server(self.port, self.children, self.vendors["alice"], self.deadline)
        self.request = partial(request, self.port, self.deadline)

    def healthy(self):
        for vendor in self.vendors.values():
            check_processes(self.children, vendor)
            require(vendor.error is None, f"media vendor error: {vendor.error}")

    def call(self, user, method, path, **kw):
        body = self.request(self.tokens[user], method, path, **kw)
        assert_hidden(body, self.secrets)
        return body

    def raw(self, user, method, path, body=None, headers=None, deadline=None):
        """-> (status, headers, bytes); raw bodies and Range, with its own large read limit."""
        end = deadline or self.deadline
        conn = http.client.HTTPConnection(HOST, self.port, timeout=remaining(end))
        try:
            head = {"Authorization": f"Bearer {self.tokens[user]}", **(headers or {})}
            try:
                conn.request(method, path, body, head)
            except (BrokenPipeError, ConnectionResetError):
                # A server may answer (e.g. 413) and close before reading an oversized body:
                # the response it already sent is still the answer we must check.
                pass
            with conn.getresponse() as response:
                data = response.read()
                require(len(data) <= 2 * CAP, "oversized library response")
                return response.status, {k.title(): v for k, v in response.getheaders()}, data
        finally:
            conn.close()

    def status(self, user, method, path, **kw):
        return self.raw(user, method, path, **kw)[0]

    # library helpers
    def upload(self, user, name, data, mime, scope="personal", space=None, expect=201):
        query = f"scope={scope}&name={quote(name, safe='')}" + (f"&space_id={quote(space, safe='')}" if space else "")
        status, _, body = self.raw(user, "POST", f"{ASSETS}?{query}", data, {"Content-Type": mime})
        require(status == expect, f"upload {name}: HTTP {status}, expected {expect}")
        if expect != 201:
            return None, body
        meta = json.loads(body)
        assert_hidden(meta, self.secrets)
        require(meta["name"] == name and meta["size_bytes"] == len(data) and meta["uploader_id"] == user
                and meta["space_id"] == (space if scope == "space" else None)
                and meta["sha256"] == hashlib.sha256(data).hexdigest()
                and meta["mime_type"] == mime and set(meta) >= {"id", "kind", "created_at"},
                "upload response is wrong about name, size, uploader, scope, hash or media type")
        return meta["id"], body

    def content(self, user, asset, **headers):
        return self.raw(user, "GET", f"{ASSETS}/{quote(asset, safe='')}/content", headers=headers)

    def index(self, user, asset, expect=(200,), segments=None):
        status, _, body = self.raw(user, "POST", f"{LIB}/index", json.dumps({"asset_id": asset}).encode(),
                                   {"Content-Type": "application/json"})
        require(status in expect, f"index: HTTP {status}, expected {expect}: {body[:200]!r}")
        if status != 200:
            return status, body
        data = json.loads(body)
        assert_hidden(data, self.secrets)
        [item] = data["items"]
        require(item["asset_id"] == asset and item["status"] == "indexed" and data["partial"] is False
                and (segments is None or item["indexed_segments"] == segments),
                "explicit index did not report the file as fully indexed")
        return status, data

    def search(self, user, query, scope, space=None, kind=None, expect=(200,)):
        body = {"query": query, "scope": scope}
        if space:
            body["space_id"] = space
        if kind:
            body["kind"] = kind
        status, _, data = self.raw(user, "POST", f"{LIB}/search", json.dumps(body).encode(),
                                   {"Content-Type": "application/json"})
        require(status in expect, f"search {query!r} {scope}: HTTP {status}, expected {expect}")
        if status != 200:
            return data
        body = json.loads(data)
        require(body["ranking"] == "embeddings" and all(h["score_kind"] == "cosine" for h in body["results"]),
                "without a classifier, results must be labelled embeddings/cosine, never reranked")
        return body["results"]

    def search_until(self, user, query, scope, check, label, space=None, seconds=20):
        """Indexing is explicit but may finish asynchronously: poll until `check(results)`."""
        end = min(self.deadline, time.monotonic() + seconds)
        while True:
            self.healthy()
            results = self.search(user, query, scope, space)
            if check(results):
                return results
            require(time.monotonic() < end, f"timed out waiting for {label}")
            time.sleep(0.1)

    def connect(self, user, kind, vendor):
        body = {"name": vendor.tag, "provider_id": kind, "model": vendor.model}
        if not kind.startswith("device-"):
            body.update(base_url=vendor.base_url, api_key=vendor.key)
        row = self.call(user, "POST", PROVIDERS, body=body, expect=(201,), read_json=True)
        require(row["provider_id"] == kind, "wrong embedding adapter created")
        return row["id"]

    def pair(self, user, connection, vendor):
        status = f"{PROVIDERS}/{quote(connection, safe='')}/device-token"
        credential = issue_token(self.request, self.tokens[user], status)
        self.secrets.append(credential)
        home = self.directory / "device-connector"
        home.mkdir(mode=0o700)
        key_file, token_file = home / "in-key", home / "in-token"
        private_file(key_file, vendor.key)
        private_file(token_file, credential)
        env = self.env | {"METRO_CONNECTOR_HOME": str(home), "METRO_CONNECTOR_POLL_MS": "50"}
        setup = start_connector(self.stack, self.connector, self.directory, env, [
            "setup", "--profile", "lib", "--server-url", f"http://{HOST}:{self.port}",
            "--kind", DEVICE_KIND, "--base-url", vendor.base_url, "--api-key-file", str(key_file),
            "--device-token-file", str(token_file), "--model", vendor.model, "--yes"])
        wait_exit(setup, self.deadline, 0, "embedding device setup")
        key_file.unlink()
        token_file.unlink()
        worker = start_connector(self.stack, self.connector, self.directory, env, ["run", "--profile", "lib"])
        self.children.append((worker, "embedding device connector"))
        wait_online(self.request, self.tokens[user], status, self.children, vendor, self.deadline)

    def use(self, user, connection, expect=(200,)):
        status = self.status(user, "PUT", f"{LIB}/settings",
                             body=json.dumps({"embedding_id": connection}).encode(),
                             headers={"Content-Type": "application/json"})
        require(status in expect, f"library settings: HTTP {status}, expected {expect}")

    def share_device(self, connection, visibility, *spaces):
        self.call("alice", "PUT", f"{PROVIDERS}/{quote(connection, safe='')}/sharing", expect=(200,),
                  body={"visibility": visibility, "space_ids": list(spaces)}, read_json=True)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def ids(results):
    return [hit["asset_id"] for hit in results]


def uniform_missing(run, user, label, real_ids, fake_scope_space):
    """Every access to an asset the user may not see must look exactly like a missing id."""
    ghost = str(uuid.uuid4())
    probes = lambda a: [  # noqa: E731
        ("GET", f"{ASSETS}/{a}", None), ("GET", f"{ASSETS}/{a}/content", None),
        ("GET", f"{ASSETS}/{a}/content", {"Range": "bytes=0-9"}),
        ("GET", f"{ASSETS}/{a}/content", {"Range": "bytes=99999999-"}),  # ACL first: never 416
        ("HEAD", f"{ASSETS}/{a}/content", None), ("DELETE", f"{ASSETS}/{a}", None)]
    baseline = [run.raw(user, m, p, headers=h)[::2] for m, p, h in probes(ghost)]
    bodies = {b for _, b in baseline}
    require({s for s, _ in baseline} == {404}, f"{label}: a missing id was not 404")
    for asset in real_ids:
        for (m, p, h), want in zip(probes(quote(asset, safe="")), baseline):
            got = run.raw(user, m, p, headers=h)
            require(got[0] == 404 and got[2].replace(asset.encode(), b"X") in
                    {b.replace(ghost.encode(), b"X") for b in bodies},
                    f"{label}: {m} {p.split('/')[-1]} was not uniformly 404")
        status, body = run.index(user, asset, expect=(404,))
        require(status == 404, f"{label}: explicit index of an invisible asset was not 404")
    for scope, space in fake_scope_space:
        require(run.status(user, "GET", f"{ASSETS}?scope={scope}&space_id={quote(space, safe='')}") == 404,
                f"{label}: listing an inaccessible Space was not 404")
        run.search(user, "crimson", scope, space, expect=(404,))
        run.upload(user, "x.txt", b"x", "text/plain", scope, space, expect=404)


