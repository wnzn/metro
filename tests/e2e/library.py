class MediaVendor(ThreadingHTTPServer):
    daemon_threads = True

    def __init__(self, tag):
        super().__init__((HOST, 0), MediaHandler)
        self.tag, self.model, self.key = tag, f"fixture/{tag}-embeddinggemma-2", token()
        self.base_url = f"http://{HOST}:{self.server_port}/v1"
        self.error = None
        self.lock = threading.Lock()
        self.calls = []        # (type, mime, sha256-of-media-or-None, query, raw-json-text, asset name)
        self.hold = None       # (predicate, arrived Event, release Event)

    def get_request(self):
        connection, address = super().get_request()
        connection.settimeout(10)
        return connection, address

    def handle_error(self, *_):
        self.error = "loopback media vendor handler failed"

    def count(self):
        with self.lock:
            return len(self.calls)

    def media(self):
        with self.lock:
            return [c[2] for c in self.calls if c[2]]

    def names(self):
        with self.lock:
            return [c[5] for c in self.calls if c[5]]

    def queries(self):
        with self.lock:
            return [c[3] for c in self.calls if c[0] == "query"]

    def wire(self):
        with self.lock:
            return "".join(c[4] for c in self.calls)

    def hold_next(self, predicate):
        state = (predicate, threading.Event(), threading.Event())
        self.hold = state
        return state[1], state[2]

    def embed(self, payload, raw):
        require(payload.get("model") == self.model, "wrong embedding model at media vendor")
        require(set(payload) in ({"model", "query"}, {"model", "asset"}),
                "vendor body must be top-level model plus exactly one of query or asset")
        if "query" in payload:
            kind, text, digest, mime, name = "query", payload["query"], None, None, None
            require(isinstance(text, str) and text, "query must be non-empty text")
        else:
            asset = payload["asset"]
            require(set(asset) == {"name", "mime_type", "data_base64"}
                    and all(isinstance(v, str) for v in asset.values()),
                    "asset must be exactly name, mime_type and base64 bytes")
            require(not asset["data_base64"].startswith(("http://", "https://", "file:", "/")),
                    "media was sent as a URL or path instead of bytes")
            data = base64.b64decode(asset["data_base64"], validate=True)
            kind, text, digest, mime, name = "asset", None, hashlib.sha256(data).hexdigest(), \
                asset["mime_type"], asset["name"]
        with self.lock:
            self.calls.append((kind, mime, digest, text, raw, name))
        hold = self.hold
        if hold and hold[0](kind, digest, text):
            self.hold = None
            hold[1].set()
            require(hold[2].wait(10), "held embedding was never released")
        if kind == "query":
            return {"model": self.model, "partial": False, "data": [
                {"index": 0, "embedding": text_vector(text), "locator": {"kind": "query"}}]}
        if mime == "image/png":
            rows = [(unit(pixel_axis(data)), {"kind": "image"}, None)]
        elif mime == "application/pdf":
            rows = [(text_vector(t), {"kind": "page", "page": n}, t[:120])
                    for n, t in enumerate(pdf_pages(data), 1)]
        elif mime == DOCX_MIME:
            rows = [(text_vector(t), {"kind": "text", "start": a, "end": b}, t)
                    for a, b, t in docx_segments(data)]
        elif mime == "text/plain":
            rows = [(text_vector(t), {"kind": "text", "start": a, "end": b}, t[:120])
                    for a, b, t in text_segments(data)]
        elif mime == "audio/wav":
            rows = [(unit(AXES["thunder"]) if rms > 1000 else text_vector(""),
                     {"kind": "time", "start_ms": a * 1000, "end_ms": b * 1000}, None)
                    for a, b, rms in wav_segments(data)]
        elif mime == "video/mp4":
            rows = [(unit(AXES["crimson"] if mp4_marker(data) == 1 else AXES["azure"]),
                     {"kind": "time", "start_ms": 0, "end_ms": 1000}, None)]
        else:
            raise RuntimeError("media vendor got an unsupported mime type")
        return {"model": self.model, "partial": False, "data": [
            {"index": i, "embedding": v, "locator": loc, **({"excerpt": ex} if ex else {})}
            for i, (v, loc, ex) in enumerate(rows)]}


class MediaHandler(BaseHTTPRequestHandler):
    def log_message(self, *_):
        pass

    def do_GET(self):
        self.reply(200 if self.path == "/v1/models" else 404,
                   {"object": "list", "data": [{"id": self.server.model, "object": "model"}]})

    def do_POST(self):
        vendor = self.server
        try:
            require(self.path == "/v1/media/embeddings", "unexpected media vendor route")
            require(self.headers.get("Authorization") == f"Bearer {vendor.key}", "wrong vendor key")
            size = int(self.headers["Content-Length"])
            require(0 < size <= 24 * 1024 * 1024, "invalid vendor request size")
            raw = self.rfile.read(size)
            body = vendor.embed(json.loads(raw), raw[:200_000].decode("latin-1"))
            self.reply(200, body)
        except Exception as exc:
            vendor.error = str(exc) if type(exc) is RuntimeError else "invalid media request"
            self.reply(400, {"error": {"message": "fixture rejected the request"}})

    def reply(self, status, body):
        data = json.dumps(body).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)


