def png(rgb, *, pad=0, tag=""):
    """A real 8x8 solid-colour PNG; the tag/padding chunk makes the bytes unique."""
    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body))
    rows = b"".join(b"\0" + bytes(rgb) * 8 for _ in range(8))
    extra = chunk(b"tEXt", b"tag\0" + tag.encode() + hashlib.sha256(tag.encode()).digest() * (pad // 32)) \
        if (tag or pad) else b""
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 8, 8, 8, 2, 0, 0, 0))
            + extra + chunk(b"IDAT", zlib.compress(rows)) + chunk(b"IEND", b""))


def pdf_doc(pages):
    """A small, structurally valid PDF 1.4 with one text line per page and a real xref."""
    objs = [b"<< /Type /Catalog /Pages 2 0 R >>",
            f"<< /Type /Pages /Kids [{' '.join(f'{3 + 2 * i} 0 R' for i in range(len(pages)))}] "
            f"/Count {len(pages)} >>".encode()]
    for i, text in enumerate(pages):
        stream = f"BT /F1 12 Tf 72 720 Td ({text}) Tj ET".encode()
        objs.append(f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents {4 + 2 * i} 0 R "
                    f"/Resources << /Font << /F1 << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> >> >> >>".encode())
        objs.append(f"<< /Length {len(stream)} >>\nstream\n".encode() + stream + b"\nendstream")
    out, offsets = bytearray(b"%PDF-1.4\n"), []
    for n, body in enumerate(objs, 1):
        offsets.append(len(out))
        out += f"{n} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    out += b"".join(f"{o:010d} 00000 n \n".encode() for o in offsets)
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)


def text_segments(data):
    """Paragraphs of a UTF-8 file with Unicode CHARACTER offsets (not bytes), shared with expectations."""
    out, pos = [], 0
    for part in data.decode().split("\n\n"):
        body = part.rstrip("\n")
        if body:
            out.append((pos, pos + len(body), body))
        pos += len(part) + 2
    return out


def docx_doc(paragraphs):
    """A minimal genuine DOCX (OPC zip: content types, package rels, word/document.xml)."""
    body = "".join(f"<w:p><w:r><w:t>{p}</w:t></w:r></w:p>" for p in paragraphs)
    parts = {
        "[Content_Types].xml": '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Default Extension="xml" ContentType="application/xml"/>'
            '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-'
            'officedocument.wordprocessingml.document.main+xml"/></Types>',
        "_rels/.rels": '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/'
            'relationships/officeDocument" Target="word/document.xml"/></Relationships>',
        "word/document.xml": '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
            f"<w:body>{body}</w:body></w:document>",
    }
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, text in parts.items():
            archive.writestr(name, text)
    return buf.getvalue()


def docx_segments(data):
    """Vendor-side extraction: paragraphs with offsets into the extracted (blank-line joined) text."""
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        xml = archive.read("word/document.xml").decode()
    out, pos = [], 0
    for text in re.findall(r"<w:t>(.*?)</w:t>", xml):
        out.append((pos, pos + len(text), text))   # character offsets into the extracted text
        pos += len(text) + 2
    return out


def pdf_pages(data):
    """Vendor-side extraction: text of each page content stream, in order."""
    return [m.decode() for m in re.findall(rb"\((.*?)\) Tj", data)]


def wav_clip(loud_second_half):
    """A valid 16-bit mono 8 kHz 10 s WAV; a loud 440 Hz tone fills the second 5 s window."""
    rate, frames = 8000, bytearray()
    for n in range(rate * 10):
        loud = loud_second_half and n >= rate * 5
        frames += struct.pack("<h", int(12000 * math.sin(2 * math.pi * 440 * n / rate)) if loud else 0)
    buf = io.BytesIO()
    with wave.open(buf, "wb") as out:
        out.setnchannels(1), out.setsampwidth(2), out.setframerate(rate)
        out.writeframes(bytes(frames))
    return buf.getvalue()


def wav_segments(data):
    """Vendor-side 'hearing': decode PCM and score each 5 s window by loudness."""
    with wave.open(io.BytesIO(data)) as clip:
        rate, raw = clip.getframerate(), clip.readframes(clip.getnframes())
    samples = struct.unpack(f"<{len(raw) // 2}h", raw)
    step, out = rate * 5, []
    for start in range(0, len(samples), step):
        window = samples[start:start + step]
        rms = math.sqrt(sum(x * x for x in window) / len(window))
        out.append((start // rate, start // rate + len(window) // rate, rms))
    return out


def mp4_clip(marker):
    """A minimal structurally valid MP4: ftyp, moov/mvhd (1 s timescale 1000) and an mdat box."""
    def box(kind, payload):
        return struct.pack(">I4s", 8 + len(payload), kind) + payload
    mvhd = box(b"mvhd", struct.pack(">IIIII", 0, 0, 0, 1000, 1000) + struct.pack(">IH", 0x10000, 0x100)
               + b"\0" * 10 + struct.pack(">9I", 0x10000, 0, 0, 0, 0x10000, 0, 0, 0, 0x40000000)
               + b"\0" * 24 + struct.pack(">I", 2))
    return (box(b"ftyp", b"isom" + struct.pack(">I", 512) + b"isomiso2mp41")
            + box(b"moov", mvhd) + box(b"mdat", bytes([marker]) * 64))


def mp4_marker(data):
    pos = 0
    while pos < len(data):
        size, kind = struct.unpack(">I4s", data[pos:pos + 8])
        if kind == b"mdat":
            return data[pos + 8]
        pos += size
    raise RuntimeError("MP4 had no mdat box")


def pixel_axis(data):
    """Vendor-side 'vision': decode the PNG pixels. Red -> crimson axis, blue -> azure axis."""
    pos, idat = 8, b""
    while pos < len(data):
        size, kind = struct.unpack(">I4s", data[pos:pos + 8])
        if kind == b"IDAT":
            idat += data[pos + 8:pos + 8 + size]
        pos += 12 + size
    r, _, b = zlib.decompress(idat)[1:4]
    return AXES["crimson"] if r > b else AXES["azure"]


def unit(axis):
    return [1.0 if i == axis else 0.0 for i in range(DIM)]


def text_vector(text):
    for word, axis in AXES.items():
        if word in text.lower():
            return unit(axis)
    return unit(DIM - 1)  # unrelated: orthogonal to every topic


