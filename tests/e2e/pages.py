#!/usr/bin/env python3
"""Black-box end-to-end test of Metro Pages.

Run with: python3 tests/e2e/pages.py [--bin-dir DIR] [--timeout SECONDS]

Needs only the real `metro-server` binary. Everything else is local: dev-token
users, a temporary on-disk SQLite database, and one scripted OpenAI-compatible
model stub on loopback that serves as the server model (METRO_MODEL). The stub
tells page-builder requests from agent turns by their system prompt.

Flow: validate (diagnostics, then keys added) -> create a Space page -> save
(and a stale save is a 409) -> read data as another member (and an outsider
gets 404) -> a button on someone else's page asks for confirmation (428), runs
as the clicker with confirm, and its answer shows on the page -> prompt to page
with one invalid model reply that is retried with diagnostics -> apply the
draft -> personal pages stay private.
"""

import argparse
from contextlib import ExitStack
from datetime import datetime, timedelta, timezone
from http.server import BaseHTTPRequestHandler, HTTPServer
import json
import math
import os
from pathlib import Path
import secrets
import signal
import sys
import threading
import time
from urllib.parse import quote

from smoke import HOST, MAX_BODY, ROOT, clean_env, content_parts, require, server_port, temp_state
from schedules import Api, Server, error_text, serve_stub

MODEL = "pages/stub"
AGENT_ANSWER = "Release is green (page e2e)."
SCHEDULE_PROMPT = "Produce a scheduled Daily brief (Pages e2e)."
SCHEDULE_ANSWER = "Daily brief from the scheduled task (Pages e2e)."
GOOD_PAGE = """```tsx
export default (
  <Page title="Generated by e2e">
    <Data name="agents" source="agents" />
    <Section key="agents" title="Agents">
      <List key="list" items={agents.items} as="a"><Text key="name">{a.name}</Text></List>
    </Section>
  </Page>
);
```"""
BAD_PAGE = "```tsx\nexport default <Page title=\"Bad\"><div onClick={() => fetch('x')} /></Page>\n```"

ASK_PAGE = """export default (
  <Page title="Release watch">
    <Data name="answer" source="agentAnswer" room="lobby" agent="agent" block="ask" />
    <Data name="agents" source="agents" />
    <AgentAnswer key="answer" from={answer} empty="No answer yet" />
    <Button label="Ask" action="runAgent" agent="agent" room="lobby"
            prompt="What is the release status?" key="ask" />
    <Stat label="Agents" value={agents.items.0.name} />
  </Page>
);"""


class Stub(HTTPServer):
    def __init__(self, api_key):
        super().__init__((HOST, 0), Handler)
        self.api_key = api_key
        self.base_url = f"http://{HOST}:{self.server_port}/v1"
        self.error = None
        self.lock = threading.Lock()
        self.builder_calls = []
        self.agent_calls = 0

    def complete(self, authorization, request):
        require(authorization == f"Bearer {self.api_key}", "stub: wrong credentials")
        require(request.get("model") == MODEL, "stub: wrong model")
        messages = request.get("messages", [])
        system = "\n".join(t for m in messages if m.get("role") == "system"
                           for t in content_parts(m.get("content")))
        users = [m for m in messages if m.get("role") == "user"]
        last = "\n".join(content_parts(users[-1].get("content"))) if users else ""
        everything = json.dumps(request)
        with self.lock:
            if "You are Metro's page builder" in system or "You are Metro's page builder" in everything:
                self.builder_calls.append(last)
                text = GOOD_PAGE if "Metro couldn't use that page" in last else BAD_PAGE
            else:
                self.agent_calls += 1
                text = SCHEDULE_ANSWER if SCHEDULE_PROMPT in last else AGENT_ANSWER
        return {
            "id": "chatcmpl-pages", "object": "chat.completion", "created": int(time.time()),
            "model": MODEL,
            "choices": [{"index": 0, "message": {"role": "assistant", "content": text},
                         "finish_reason": "stop"}],
            "usage": {"prompt_tokens": 1, "completion_tokens": 1, "total_tokens": 2},
        }


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *_):
        pass

    def do_POST(self):
        stub = self.server
        try:
            require(self.path == "/v1/chat/completions", "stub: unexpected path")
            size = int(self.headers["Content-Length"])
            require(0 < size <= MAX_BODY, "stub: invalid request size")
            body = stub.complete(self.headers.get("Authorization"), json.loads(self.rfile.read(size)))
            status = 200
        except Exception as exc:
            detail = str(exc) if type(exc) is RuntimeError else "invalid completion request"
            stub.error = stub.error or detail
            body, status = {"error": {"message": detail}}, 400
        data = json.dumps(body).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)


def poll(deadline, what, fn, watch):
    while time.monotonic() < deadline:
        for check in watch:
            check()
        value = fn()
        if value is not None:
            return value
        time.sleep(0.1)
    raise RuntimeError(f"timed out waiting for {what}")


def pages(binary, timeout):
    deadline = time.monotonic() + timeout
    tokens = {name: secrets.token_hex(24) for name in ("alice", "bob", "carol")}
    api_key = secrets.token_hex(16)
    with temp_state() as directory, ExitStack() as stack:
        state = Path(directory)
        stub = serve_stub(stack, Stub(api_key))
        port = server_port()
        env = clean_env(directory) | {
            "METRO_BIND": f"{HOST}:{port}",
            "METRO_DB": str(state / "pages.sqlite"),
            "METRO_DEV_USERS": json.dumps(tokens),
            "METRO_MODEL": MODEL,
            "METRO_MODEL_BASE_URL": stub.base_url,
            "METRO_MODEL_API_KEY": api_key,
        }
        server = Server(stack, binary, state, env, port, stub)
        server.start(deadline)
        api = Api(server, deadline)
        alice, bob, carol = tokens["alice"], tokens["bob"], tokens["carol"]

        def watch_all():
            require(stub.error is None, stub.error or "")
            require(server.alive(), "metro-server exited unexpectedly")

        watch = [watch_all]
        _, space = api.ok(alice, "POST", "/v1/spaces", {"name": "Pages Space"}, (201,))
        sid = space["id"]
        api.ok(alice, "POST", f"/v1/spaces/{quote(sid)}/members", {"user_id": "bob"}, (201,))
        scope = {"scope": "space", "space_id": sid}

        # Validate: diagnostics for code, keys added for a good page. No model is called.
        _, v = api.ok(bob, "POST", "/v1/pages/validate",
                      scope | {"source": "export default <Page title=\"x\"><script/></Page>"}, (200,))
        require(v["ok"] is False and "HTML elements" in v["diagnostics"][0]["message"],
                f"validate accepted code: {v}")
        _, v = api.ok(bob, "POST", "/v1/pages/validate", scope | {"source": ASK_PAGE}, (200,))
        require(v["ok"] is True and 'key="stat-1"' in v["source"], f"validate: {error_text(v)}")
        require(not stub.builder_calls and stub.agent_calls == 0, "validation reached a model")

        # Create and save, with optimistic concurrency.
        _, page = api.ok(bob, "POST", "/v1/pages", scope | {"source": ASK_PAGE}, (201,))
        pid = page["id"]
        require(page["head_version"] == 1 and page["can_edit"] is True, f"create: {page}")
        _, page = api.ok(bob, "POST", f"/v1/pages/{pid}/versions",
                         {"base_version": 1, "source": page["source"].replace("Release watch", "Release")},
                         (201,))
        require(page["head_version"] == 2 and page["title"] == "Release", f"save: {page}")
        status, data = api.raw(bob, "POST", f"/v1/pages/{pid}/versions",
                               {"base_version": 1, "source": ASK_PAGE})
        require(status == 409 and data["head_version"] == 2, f"stale save: HTTP {status}")

        # Data as another member; outsiders see nothing.
        _, d = api.ok(alice, "POST", f"/v1/pages/{pid}/data", {}, (200,))
        require(d["data"]["agents"]["ok"] is True, f"data: {d}")
        require(d["actions"]["ask"]["enabled"] is True and d["actions"]["ask"]["confirm"] is True,
                f"button for Alice: {d['actions']}")
        for method, path, body in (("GET", f"/v1/pages/{pid}", None),
                                   ("POST", f"/v1/pages/{pid}/data", {}),
                                   ("POST", f"/v1/pages/{pid}/actions", {"version": 2, "block_key": "ask"})):
            status, _ = api.raw(carol, method, path, body)
            require(status == 404, f"outsider {method} {path}: HTTP {status}")
        _, listed = api.ok(carol, "GET", "/v1/pages", expect=(200,))
        require(listed["pages"] == [], "an outsider listed a Space page")

        # A button on Bob's page: Alice confirms once, and the run is hers.
        status, c = api.raw(alice, "POST", f"/v1/pages/{pid}/actions", {"version": 2, "block_key": "ask"})
        require(status == 428 and c["confirmation"]["action"]["prompt"] == "What is the release status?"
                and c["confirmation"]["runs_as"] == "alice", f"confirmation: HTTP {status}")
        _, r = api.ok(alice, "POST", f"/v1/pages/{pid}/actions",
                      {"version": 2, "block_key": "ask", "confirm": True}, (202,))
        require(r["started"] is True, f"action: {r}")

        def answered():
            _, d = api.ok(bob, "POST", f"/v1/pages/{pid}/data", {}, (200,))
            value = d["data"]["answer"].get("value")
            return value if value and value.get("status") == "done" else None

        answer = poll(deadline, "the button's answer", answered, watch)
        require(answer["text"] == AGENT_ANSWER, f"answer: {answer}")
        _, events = api.ok(bob, "GET", f"/v1/spaces/{quote(sid)}/rooms/lobby/events", expect=(200,))
        require(any(e["kind"] == "message" and e["actor_id"] == "alice"
                    and e["text"] == "What is the release status?" for e in events["events"]),
                "the trigger message wasn't Alice's")
        status, _ = api.raw(alice, "POST", f"/v1/pages/{pid}/actions", {"version": 2, "block_key": "ask"})
        require(status == 202, f"second click asked again: HTTP {status}")

        # Prompt to page: one invalid reply, retried with diagnostics, then applied.
        _, draft = api.ok(alice, "POST", "/v1/pages/drafts", scope | {"prompt": "Show this Space's agents"},
                          (202,))
        did = draft["id"]
        status, _ = api.raw(bob, "GET", f"/v1/pages/drafts/{did}")
        require(status == 404, f"another member saw a draft: HTTP {status}")

        def finished():
            _, d = api.ok(alice, "GET", f"/v1/pages/drafts/{did}", expect=(200,))
            return d if d["status"] != "generating" else None

        draft = poll(deadline, "the draft", finished, watch)
        require(draft["status"] == "ready" and draft["attempts"] == 2, f"draft: {draft}")
        require(len(stub.builder_calls) == 2 and "HTML elements" in stub.builder_calls[1],
                "the retry didn't carry the diagnostics")
        _, preview = api.ok(alice, "POST", f"/v1/pages/drafts/{did}/data", {}, (200,))
        require(preview["data"]["agents"]["ok"] is True, f"preview: {preview}")
        _, made = api.ok(alice, "POST", f"/v1/pages/drafts/{did}/apply", {}, (201,))
        require(made["title"] == "Generated by e2e" and made["version"]["kind"] == "create"
                and made["version"]["model"] == f"server/{MODEL}", f"applied: {made}")

        # Space Daily brief follows the room and its selected agent, not a
        # page-button origin. Exercise a real schedule dispatch on loopback.
        _, room = api.ok(alice, "POST", f"/v1/spaces/{quote(sid)}/rooms", {"name": "Briefing"}, (201,))
        _, brief_page = api.ok(
            alice, "POST", "/v1/pages", scope | {"template": "daily-brief", "room": room["name"]}, (201,))
        target = brief_page["spec"]["data"][0]["params"]
        require("block" not in target and target.get("room_id") == room["id"] and bool(target.get("agent_id")),
                "Space Daily brief isn't bound to a room and an agent")
        brief_data = f"/v1/pages/{brief_page['id']}/data"
        _, empty_brief = api.ok(bob, "POST", brief_data, {}, (200,))
        require(empty_brief["data"]["brief"].get("value") is None, "the Lobby answer leaked into the Briefing block")
        _, task = api.ok(alice, "POST", "/v1/schedules", {
            "name": "Scheduled fixture brief",
            "prompt": SCHEDULE_PROMPT,
            "space_id": sid,
            "room_id": target["room_id"],
            "schedule": {"kind": "once", "at": (datetime.now(timezone.utc) + timedelta(days=1)).isoformat()},
        }, (201,))
        _, schedule_page = api.ok(bob, "POST", "/v1/pages", scope | {
            "source": f'export default <Page title="Schedule"><Button key="run" label="Run" '
                      f'action="runSchedule" schedule="{task["id"]}"/></Page>',
        }, (201,))
        click_path = f"/v1/pages/{schedule_page['id']}/actions"
        click = {"version": 1, "block_key": "run"}
        status, challenge = api.raw(alice, "POST", click_path, click)
        require(status == 428, f"scheduled page action didn't ask for consent: HTTP {status}")
        action = challenge["confirmation"]["action"]
        require(action["room_id"] == target["room_id"] and action["prompt"] == SCHEDULE_PROMPT,
                "scheduled page action did not describe the claimed task's destination and prompt")
        _, run = api.ok(alice, "POST", click_path,
                        click | {"confirm": True, "schedule_revision": action["schedule_revision"]}, (200,))
        require(run["run"]["status"] == "dispatched", "scheduled page action did not dispatch")

        def scheduled_brief():
            _, data = api.ok(bob, "POST", brief_data, {}, (200,))
            answer = data["data"]["brief"].get("value")
            return answer if answer and answer.get("text") == SCHEDULE_ANSWER else None

        answer = poll(deadline, "a scheduled reply on the Space Daily brief", scheduled_brief, watch)
        require(answer.get("room") == target["room"], "Daily brief didn't read its scheduled room")

        # A newer reply in the right room, but from a different agent, doesn't
        # replace the selected agent's brief.
        _, helper = api.ok(alice, "POST", f"/v1/spaces/{quote(sid)}/agents", {
            "name": "Briefing helper", "handle": "briefing-helper", "description": "Loopback fixture",
        }, (201,))
        _, helper_page = api.ok(alice, "POST", "/v1/pages", scope | {
            "source": 'export default <Page title="Helper"><Button key="ask" label="Ask" action="runAgent" '
                      'room="Briefing" agent="briefing-helper" prompt="Send a different reply"/></Page>',
        }, (201,))
        api.ok(alice, "POST", f"/v1/pages/{helper_page['id']}/actions", {"version": 1, "block_key": "ask"}, (202,))

        def helper_replied():
            path = f"/v1/spaces/{quote(sid)}/rooms/{quote(room['id'])}/events"
            _, data = api.ok(bob, "GET", path, expect=(200,))
            return next((e for e in data["events"] if e["kind"] == "agent"
                         and (e.get("activity") or {}).get("agent", {}).get("id") == helper["id"]), None)

        poll(deadline, "the other agent's newer reply", helper_replied, watch)
        require(scheduled_brief() is not None, "another agent's newer reply replaced the scheduled brief")

        # Personal Daily brief stays private and linked to its own button.
        _, mine = api.ok(alice, "POST", "/v1/pages", {"scope": "personal", "template": "daily-brief"}, (201,))
        private_target = mine["spec"]["data"][0]["params"]
        require(private_target.get("chat") is True and private_target.get("block") == "ask",
                "personal Daily brief doesn't only follow its page button")
        _, private = api.ok(alice, "POST", f"/v1/pages/{mine['id']}/data", {}, (200,))
        require(private["data"]["brief"].get("value") is None, "Space brief appeared on a personal page")
        api.ok(alice, "POST", f"/v1/pages/{mine['id']}/actions", {"version": 1, "block_key": "ask"}, (202,))

        def personal_brief():
            _, data = api.ok(alice, "POST", f"/v1/pages/{mine['id']}/data", {}, (200,))
            answer = data["data"]["brief"].get("value")
            return answer if answer and answer.get("text") == AGENT_ANSWER else None

        poll(deadline, "the private Daily brief's button answer", personal_brief, watch)
        for token in (bob, carol):
            status, _ = api.raw(token, "GET", f"/v1/pages/{mine['id']}")
            require(status == 404, f"personal page visible to someone else: HTTP {status}")
        watch_all()
    print("PASS: validate refused code and added keys without a model; create, save and a stale-save "
          "409; data as a member, 404 for an outsider; a button on someone else's page asked once "
          "(428), ran as the clicker and its answer showed on the page; prompt to page retried "
          "with diagnostics and applied; scheduled reply appeared on the Space Daily brief; "
          "personal Daily brief stayed private and followed its own button.")


def terminate(signum, _frame):
    raise SystemExit(128 + signum)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bin-dir", type=Path, default=ROOT / "target" / "debug")
    parser.add_argument("--timeout", type=float, default=60, help="overall deadline in seconds")
    args = parser.parse_args()
    if not math.isfinite(args.timeout) or args.timeout <= 0:
        parser.error("--timeout must be finite and positive")
    binary = args.bin_dir.resolve() / "metro-server"
    if not binary.is_file() or not os.access(binary, os.X_OK):
        parser.error(f"missing executable {binary}; build metro-server or set --bin-dir")
    try:
        pages(binary, args.timeout)
    except (KeyError, TypeError, AttributeError, IndexError) as exc:
        print(f"FAIL: unexpected response shape ({type(exc).__name__}: {exc})", file=sys.stderr)
        return 1
    except (RuntimeError, OSError, ValueError, TimeoutError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 130
    return 0


if __name__ == "__main__":
    signal.signal(signal.SIGTERM, terminate)
    raise SystemExit(main())
